/** Fisher–Yates shuffle — returns a new array, leaves the input untouched. */
export function shuffle<T>(items: readonly T[]): T[] {
  const a = [...items];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j]!, a[i]!];
  }
  return a;
}

/** Split a list into `n` round-robin rows (keeps each row a similar length and
 *  interleaves items so adjacent rows don't mirror each other). */
export function intoRows<T>(items: readonly T[], n: number): T[][] {
  const rows: T[][] = Array.from({ length: n }, () => []);
  items.forEach((item, i) => rows[i % n]!.push(item));
  return rows;
}
